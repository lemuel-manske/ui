#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { parseArgs } from 'node:util';

import { parse, TYPE, type MessageFormatElement } from '@formatjs/icu-messageformat-parser';

type Catalog = Map<string, Set<string>>;

function collectArguments(elements: MessageFormatElement[], names: Set<string>) {
  for (const element of elements) {
    switch (element.type) {
      case TYPE.select:
      case TYPE.plural:
        names.add(element.value);

        for (const { value } of Object.values(element.options)) {
          collectArguments(value, names);
        }

        break;
      case TYPE.argument:
      case TYPE.number:
      case TYPE.date:
      case TYPE.time:
        names.add(element.value);
        break;
    }
  }
}

async function readCatalog(path: string): Promise<Catalog> {
  const data: unknown = JSON.parse(await readFile(path, 'utf8'));

  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    throw new Error(`${path}: expected a JSON object containing message strings.`);
  }

  const catalog: Catalog = new Map();

  for (const [id, value] of Object.entries(data)) {
    if (!/^[a-z][a-z0-9_-]*(?:\.[a-z0-9][a-z0-9_-]*)*$/.test(id) || typeof value !== 'string') {
      throw new Error(`${path}: invalid message ID or value at ${JSON.stringify(id)}.`);
    }

    const argumentsUsed = new Set<string>();

    try {
      collectArguments(parse(value, { ignoreTag: true }), argumentsUsed);
    } catch (error) {
      throw new Error(`${path}: invalid ICU message at ${id}: ${(error as Error).message}`, {
        cause: error,
      });
    }

    catalog.set(id, argumentsUsed);
  }

  return catalog;
}

function validateTranslation(path: string, translated: Catalog, defaults: Catalog) {
  for (const [id, argumentsUsed] of translated) {
    const expected = defaults.get(id);

    if (!expected) {
      throw new Error(`${path}: unknown message ID ${id}.`);
    }

    if (
      expected.size !== argumentsUsed.size ||
      [...expected].some((name) => !argumentsUsed.has(name))
    ) {
      throw new Error(`${path}: placeholders for ${id} must match the default catalog.`);
    }
  }
}

function generateConstants(catalog: Catalog) {
  const constants = new Map<string, string>();

  for (const id of [...catalog.keys()].sort()) {
    const name = id.replace(/[.-]/g, '_').toUpperCase();
    const conflictingId = constants.get(name);

    if (conflictingId !== undefined) {
      throw new Error(`Message IDs ${conflictingId} and ${id} both generate ${name}.`);
    }

    constants.set(name, id);
  }

  return [
    '// Generated by i18n-message-ids. Edit the default locale catalog to change this file.',
    "import type { MessageId } from '@lemuel-manske/i18n';",
    ...[...constants].map(
      ([name, id]) => `\nexport const ${name} = '${id}' as MessageId<'${id}'>;`,
    ),
    '',
  ].join('\n');
}

async function run() {
  const {
    positionals: [defaultPath, outputPath, ...translationPaths],
    values: { check },
  } = parseArgs({
    allowPositionals: true,
    options: { check: { type: 'boolean' } },
  });

  if (!defaultPath || !outputPath) {
    throw new Error(
      'Usage: i18n-message-ids [--check] <default.json> <message-ids.ts> [locale.json ...]',
    );
  }

  const defaults = await readCatalog(defaultPath);

  for (const path of translationPaths) {
    validateTranslation(path, await readCatalog(path), defaults);
  }

  const output = generateConstants(defaults);

  if (check) {
    const existing = await readFile(outputPath, 'utf8').catch((error: NodeJS.ErrnoException) => {
      if (error.code !== 'ENOENT') {
        throw error;
      }
    });

    if (existing !== output) {
      throw new Error(
        `${outputPath} is missing or out of date. Run i18n-message-ids without --check.`,
      );
    }

    return;
  }

  await writeFile(outputPath, output);
}

try {
  await run();
} catch (error) {
  console.error((error as Error).message);
  process.exitCode = 1;
}
